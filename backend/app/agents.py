def public_view() -> list:
    """返回给前端展示的字段（不泄露系统提示词）。"""
    return [
        {"id": a["id"], "name": a["name"], "ico": a["ico"], "group": a["group"],
         "desc": a["desc"], "suggestions": a["suggestions"]}
        for a in AGENTS
    ]


def system_prompt(agent_id: str) -> str:
    return AGENTS_BY_ID.get(agent_id, AGENTS_BY_ID["command"])["system"]


